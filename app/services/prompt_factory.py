_INTENT_HINTS = {
    QueryIntent.TEST_LOOKUP: "عرّف التحليل بإيجاز (سطر فائدة واحد) واقترح مكمّلاً عند توفره. لا تستخدم \"متوفر عندنا ✅\" هنا.",
    QueryIntent.SYMPTOM_QUERY: "اعرض حتى ٣ تحاليل بأسمائها الإنجليزية فقط دون تشخيص، ثم اطلب رقم الجوال بجملة واحدة. لا تخترع تحليلاً ثالثاً إذا لم يتوفر.",
    QueryIntent.FASTING_PREP: "أجب أولاً بنعم/لا للصيام، ثم عدد الساعات وتعليمة تحضير واحدة. سطرين كحد أقصى. لا تطلب رقم الجوال — هذا سؤال معلوماتي بحت.",
    QueryIntent.AVAILABILITY: "وضّح توفر التحليل باستخدام \"متوفر عندنا ✅\" (هذا هو السياق الوحيد المسموح فيه بهذه العبارة)، دون سعر، واطلب رقم الجوال للمتابعة.",
    QueryIntent.PACKAGE_INQUIRY: "اعرض حتى ٣ باقات ذات صلة بإيجاز دون أسعار.",
    QueryIntent.AMBIGUOUS: "اطرح سؤالاً توضيحياً واحداً قصيراً لتحديد التحليل المقصود، أو إذا كان الاسم غير معروف استخدم قالب \"ما عرفت القصد\".",
    QueryIntent.GENERAL: "رحّب بجملة واحدة واسأل كيف تقدر تساعد في تحاليل وريد.",
}


def build_system_prompt(context: str, intent: QueryIntent) -> str:
    """Compose the final system prompt from the base rules, an intent hint, and context."""
    hint = _INTENT_HINTS.get(intent, "")
    ctx = context.strip() if context else "لا يوجد سياق مسترجع."
    return f"{BASE_SYSTEM_PROMPT}\n\nإرشاد حسب نوع السؤال: {hint}\n\nالسياق المتاح:\n{ctx}"
